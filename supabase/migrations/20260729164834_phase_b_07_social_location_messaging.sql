create or replace function private.ensure_direct_conversation() returns trigger language plpgsql security definer set search_path='' as $$
declare v_conversation_id uuid;
begin
 if new.status='accepted'::public.friendship_status and old.status is distinct from new.status then
  insert into public.conversations(friendship_id) values(new.id) on conflict(friendship_id) do update set updated_at=now() returning id into v_conversation_id;
  insert into public.conversation_members(conversation_id,user_id) values(v_conversation_id,new.requester_id),(v_conversation_id,new.addressee_id) on conflict(conversation_id,user_id) do nothing;
 end if;
 return new;
end $$;
revoke all on function private.ensure_direct_conversation() from public,anon,authenticated;
create trigger friendships_create_direct_conversation after update of status on public.friendships for each row execute function private.ensure_direct_conversation();

create or replace function private.validate_message_insert() returns trigger language plpgsql security definer set search_path='' as $$
declare v_friendship public.friendships%rowtype; v_other_user uuid;
begin
 if not private.is_conversation_member(new.conversation_id,new.sender_id) then raise exception using errcode='42501',message='sender_not_conversation_member'; end if;
 select f.* into v_friendship from public.conversations c join public.friendships f on f.id=c.friendship_id where c.id=new.conversation_id;
 if not found or v_friendship.status<>'accepted'::public.friendship_status then raise exception using errcode='42501',message='accepted_friendship_required'; end if;
 v_other_user:=case when v_friendship.requester_id=new.sender_id then v_friendship.addressee_id else v_friendship.requester_id end;
 if private.users_are_blocked(new.sender_id,v_other_user) then raise exception using errcode='42501',message='messaging_blocked'; end if;
 return new;
end $$;
revoke all on function private.validate_message_insert() from public,anon,authenticated;
create trigger messages_validate_insert before insert on public.messages for each row execute function private.validate_message_insert();

create or replace function public.set_my_location(p_latitude double precision,p_longitude double precision,p_accuracy_meters integer,p_captured_at timestamptz,p_source text default 'device_foreground')
returns table(is_enabled boolean,captured_at timestamptz,expires_at timestamptz) language plpgsql security definer set search_path='' as $$
declare v_user_id uuid:=auth.uid(); v_now timestamptz:=now(); v_max_accuracy integer; v_stale_days integer; v_expires_at timestamptz;
begin
 if v_user_id is null then raise exception using errcode='42501',message='authentication_required'; end if;
 if not private.is_active_adult(v_user_id) then raise exception using errcode='42501',message='active_adult_account_required'; end if;
 if p_latitude is null or p_latitude < -90 or p_latitude > 90 or p_longitude is null or p_longitude < -180 or p_longitude > 180 then raise exception using errcode='22023',message='invalid_coordinates'; end if;
 if p_accuracy_meters is null or p_accuracy_meters<0 then raise exception using errcode='22023',message='invalid_location_accuracy'; end if;
 if p_captured_at is null or p_captured_at>v_now+interval '5 minutes' or p_captured_at<v_now-interval '24 hours' then raise exception using errcode='22023',message='invalid_location_capture_time'; end if;
 if p_source not in ('device_foreground','device_approximate') then raise exception using errcode='22023',message='invalid_location_source'; end if;
 select (value_json#>>'{}')::integer into v_max_accuracy from private.app_config where key='location_max_accuracy_meters';
 select (value_json#>>'{}')::integer into v_stale_days from private.app_config where key='location_stale_after_days';
 if p_accuracy_meters>coalesce(v_max_accuracy,5000) then raise exception using errcode='22023',message='location_accuracy_too_low'; end if;
 if exists(select 1 from private.location_events e where e.user_id=v_user_id and e.event_type='set' and e.occurred_at>v_now-interval '30 seconds') then raise exception using errcode='54000',message='location_update_rate_limited'; end if;
 v_expires_at:=p_captured_at+make_interval(days=>coalesce(v_stale_days,7));
 insert into private.user_locations(user_id,location,accuracy_meters,captured_at,consented_at,is_enabled,source,expires_at)
 values(v_user_id,extensions.st_setsrid(extensions.st_makepoint(p_longitude,p_latitude),4326)::extensions.geography,p_accuracy_meters,p_captured_at,v_now,true,p_source,v_expires_at)
 on conflict(user_id) do update set location=excluded.location,accuracy_meters=excluded.accuracy_meters,captured_at=excluded.captured_at,consented_at=excluded.consented_at,is_enabled=true,source=excluded.source,expires_at=excluded.expires_at;
 insert into private.location_events(user_id,event_type,source,accuracy_meters) values(v_user_id,'set',p_source,p_accuracy_meters);
 return query select true,p_captured_at,v_expires_at;
end $$;
revoke all on function public.set_my_location(double precision,double precision,integer,timestamptz,text) from public,anon;
grant execute on function public.set_my_location(double precision,double precision,integer,timestamptz,text) to authenticated;

create or replace function public.disable_my_location() returns boolean language plpgsql security definer set search_path='' as $$
declare v_user_id uuid:=auth.uid(); v_updated integer:=0;
begin
 if v_user_id is null then raise exception using errcode='42501',message='authentication_required'; end if;
 update private.user_locations set is_enabled=false,expires_at=least(expires_at,now()) where user_id=v_user_id;
 get diagnostics v_updated=row_count;
 insert into private.location_events(user_id,event_type) values(v_user_id,'disable');
 return v_updated>0;
end $$;
revoke all on function public.disable_my_location() from public,anon;
grant execute on function public.disable_my_location() to authenticated;

create or replace function public.find_nearby_profiles(p_radius_meters integer default 8000,p_limit integer default 20,p_cursor uuid default null)
returns table(id uuid,username text,display_name text,bio text,gender public.gender_identity,province_id bigint,avatar_media_id uuid,is_creator boolean,distance_bucket text)
language sql stable security definer set search_path='' as $$
 with caller as (
  select ul.location,
   least(greatest(coalesce(p_radius_meters,8000),1),coalesce((select (c.value_json#>>'{}')::integer from private.app_config c where c.key='location_max_radius_meters'),15000))::double precision radius_meters,
   least(greatest(coalesce(p_limit,20),1),50) result_limit,
   coalesce((select (c.value_json#>>'{}')::integer from private.app_config c where c.key='location_max_accuracy_meters'),5000) max_accuracy
  from private.user_locations ul join public.profiles cp on cp.id=ul.user_id
  where ul.user_id=auth.uid() and cp.discovery_enabled and cp.nearby_enabled and ul.is_enabled and ul.expires_at>now() and private.is_active_adult(ul.user_id)
 ), candidates as (
  select p.id,p.username::text username,p.display_name,p.bio,p.gender,p.province_id,p.avatar_media_id,p.is_creator,
   extensions.st_distance(ul.location,caller.location) distance_meters,caller.result_limit
  from caller join private.user_locations ul on ul.user_id<>auth.uid() and ul.is_enabled and ul.expires_at>now() and ul.accuracy_meters<=caller.max_accuracy and extensions.st_dwithin(ul.location,caller.location,caller.radius_meters)
  join public.profiles p on p.id=ul.user_id
  where p.profile_status='active'::public.profile_status and p.deleted_at is null and p.discovery_enabled and p.nearby_enabled and private.is_active_adult(p.id) and not private.users_are_blocked(auth.uid(),p.id)
 ), cursor_distance as (select c.distance_meters from candidates c where c.id=p_cursor)
 select c.id,c.username,c.display_name,c.bio,c.gender,c.province_id,c.avatar_media_id,c.is_creator,private.distance_bucket(c.distance_meters)
 from candidates c
 where p_cursor is null or (c.distance_meters,c.id)>((select distance_meters from cursor_distance),p_cursor)
 order by c.distance_meters,c.id
 limit (select result_limit from caller)
$$;
revoke all on function public.find_nearby_profiles(integer,integer,uuid) from public,anon;
grant execute on function public.find_nearby_profiles(integer,integer,uuid) to authenticated;

