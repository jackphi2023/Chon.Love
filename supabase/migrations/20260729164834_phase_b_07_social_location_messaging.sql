create or replace function public.send_friend_request(p_addressee_id uuid,p_greeting_message text default null) returns public.friendships language plpgsql security definer set search_path='' as $$
declare v_user_id uuid:=auth.uid(); v_result public.friendships;
begin
 if v_user_id is null then raise exception using errcode='42501',message='authentication_required'; end if;
 if p_addressee_id is null or p_addressee_id=v_user_id then raise exception using errcode='22023',message='invalid_friend_target'; end if;
 if not private.is_active_adult(v_user_id) or not private.is_active_adult(p_addressee_id) then raise exception using errcode='42501',message='active_adult_accounts_required'; end if;
 if private.users_are_blocked(v_user_id,p_addressee_id) then raise exception using errcode='42501',message='friendship_blocked'; end if;
 if p_greeting_message is not null and char_length(p_greeting_message)>280 then raise exception using errcode='22001',message='greeting_too_long'; end if;
 if exists(select 1 from public.friendships f where f.pair_low_id=least(v_user_id,p_addressee_id) and f.pair_high_id=greatest(v_user_id,p_addressee_id) and f.status in ('pending','accepted')) then raise exception using errcode='23505',message='active_friendship_exists'; end if;
 insert into public.friendships(requester_id,addressee_id,greeting_message) values(v_user_id,p_addressee_id,nullif(btrim(p_greeting_message),'')) returning * into v_result;
 return v_result;
end $$;
revoke all on function public.send_friend_request(uuid,text) from public,anon;
grant execute on function public.send_friend_request(uuid,text) to authenticated;

create or replace function public.respond_to_friend_request(p_friendship_id uuid,p_accept boolean) returns public.friendships language plpgsql security definer set search_path='' as $$
declare v_user_id uuid:=auth.uid(); v_result public.friendships;
begin
 if v_user_id is null then raise exception using errcode='42501',message='authentication_required'; end if;
 update public.friendships f set status=case when p_accept then 'accepted'::public.friendship_status else 'declined'::public.friendship_status end,responded_at=now()
 where f.id=p_friendship_id and f.addressee_id=v_user_id and f.status='pending'::public.friendship_status and not private.users_are_blocked(f.requester_id,f.addressee_id) returning * into v_result;
 if v_result.id is null then raise exception using errcode='42501',message='pending_request_not_available'; end if;
 return v_result;
end $$;
revoke all on function public.respond_to_friend_request(uuid,boolean) from public,anon;
grant execute on function public.respond_to_friend_request(uuid,boolean) to authenticated;

