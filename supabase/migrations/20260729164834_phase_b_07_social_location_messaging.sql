create type public.friendship_status as enum ('pending','accepted','declined','cancelled');
create type public.report_status as enum ('submitted','triaged','in_review','resolved','dismissed');
create type public.report_priority as enum ('low','normal','high','urgent');
create type public.conversation_type as enum ('direct');
create type public.message_type as enum ('text','gift','system');
create type public.message_moderation_status as enum ('unreviewed','approved','flagged','removed');

create table private.user_locations (
  user_id uuid primary key references auth.users(id) on delete cascade,
  location extensions.geography(Point,4326) not null,
  accuracy_meters integer not null,
  captured_at timestamptz not null,
  consented_at timestamptz not null,
  is_enabled boolean not null default true,
  source text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_locations_accuracy_nonnegative check (accuracy_meters>=0),
  constraint user_locations_accuracy_reasonable check (accuracy_meters<=50000),
  constraint user_locations_captured_not_future check (captured_at<=now()+interval '5 minutes'),
  constraint user_locations_expiry_after_capture check (expires_at>captured_at),
  constraint user_locations_enabled_requires_consent check (not is_enabled or consented_at is not null),
  constraint user_locations_source_check check (source in ('device_foreground','device_approximate'))
);
comment on table private.user_locations is 'Exact user coordinates. Server-only and absent from public generated types.';
create index user_locations_location_gist on private.user_locations using gist(location);
create index user_locations_enabled_expiry_idx on private.user_locations(expires_at,captured_at,user_id) where is_enabled;
create trigger user_locations_set_updated_at before update on private.user_locations for each row execute function private.set_updated_at();

create table private.location_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  source text,
  accuracy_meters integer,
  occurred_at timestamptz not null default now(),
  constraint location_events_type_check check (event_type in ('set','disable')),
  constraint location_events_accuracy_nonnegative check (accuracy_meters is null or accuracy_meters>=0)
);
comment on table private.location_events is 'Immutable location audit without coordinates.';
create index location_events_user_occurred_idx on private.location_events(user_id,occurred_at desc);

create table public.friendships (
  id uuid primary key default extensions.gen_random_uuid(),
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  pair_low_id uuid generated always as (least(requester_id,addressee_id)) stored,
  pair_high_id uuid generated always as (greatest(requester_id,addressee_id)) stored,
  status public.friendship_status not null default 'pending',
  greeting_message text,
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint friendships_not_self check (requester_id<>addressee_id),
  constraint friendships_greeting_length check (greeting_message is null or char_length(greeting_message)<=280),
  constraint friendships_response_timestamp check ((status='pending' and responded_at is null) or (status<>'pending' and responded_at is not null))
);
create unique index friendships_active_pair_unique_idx on public.friendships(pair_low_id,pair_high_id) where status in ('pending','accepted');
create index friendships_requester_status_created_idx on public.friendships(requester_id,status,created_at desc);
create index friendships_addressee_status_created_idx on public.friendships(addressee_id,status,created_at desc);
create index friendships_pair_history_idx on public.friendships(pair_low_id,pair_high_id,created_at desc);
create trigger friendships_set_updated_at before update on public.friendships for each row execute function private.set_updated_at();

