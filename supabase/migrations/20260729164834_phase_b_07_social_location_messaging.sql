create or replace function public.send_message(p_conversation_id uuid,p_body text,p_client_message_id uuid) returns public.messages language plpgsql security definer set search_path='' as $$
declare v_user_id uuid:=auth.uid(); v_result public.messages;
begin
 if v_user_id is null then raise exception using errcode='42501',message='authentication_required'; end if;
 if not private.is_active_adult(v_user_id) then raise exception using errcode='42501',message='active_adult_account_required'; end if;
 if p_client_message_id is null then raise exception using errcode='22023',message='client_message_id_required'; end if;
 if nullif(btrim(p_body),'') is null or char_length(p_body)>2000 then raise exception using errcode='22023',message='invalid_message_body'; end if;
 insert into public.messages(conversation_id,sender_id,message_type,body,client_message_id) values(p_conversation_id,v_user_id,'text'::public.message_type,btrim(p_body),p_client_message_id)
 on conflict(sender_id,client_message_id) do update set sender_id=excluded.sender_id returning * into v_result;
 update public.conversations set last_message_at=v_result.sent_at where id=p_conversation_id;
 return v_result;
end $$;
