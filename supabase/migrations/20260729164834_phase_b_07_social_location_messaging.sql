create or replace function private.is_active_adult(p_user_id uuid) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.profiles p join private.user_identity i on i.user_id=p.id where p.id=p_user_id and p.profile_status='active'::public.profile_status and p.deleted_at is null and i.account_status='active'::private.account_status and i.age_verified_at is not null and i.date_of_birth<=(current_date-interval '18 years')::date and i.terms_accepted_at is not null and i.community_rules_accepted_at is not null)
$$;
create or replace function private.users_are_blocked(p_user_a uuid,p_user_b uuid) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.user_blocks b where (b.blocker_id=p_user_a and b.blocked_id=p_user_b) or (b.blocker_id=p_user_b and b.blocked_id=p_user_a))
$$;
create or replace function private.is_conversation_member(p_conversation_id uuid,p_user_id uuid) returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.conversation_members cm where cm.conversation_id=p_conversation_id and cm.user_id=p_user_id)
$$;
create or replace function private.distance_bucket(p_distance_meters double precision) returns text language sql immutable set search_path='' as $$
 select case when p_distance_meters<1000 then 'under_1km' when p_distance_meters<3000 then '1_to_3km' when p_distance_meters<5000 then '3_to_5km' when p_distance_meters<8000 then '5_to_8km' when p_distance_meters<15000 then '8_to_15km' else 'over_15km' end
$$;
