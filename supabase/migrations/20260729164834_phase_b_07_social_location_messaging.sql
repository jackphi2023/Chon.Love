create or replace function public.block_user(p_blocked_id uuid,p_reason_code text default null) returns boolean language plpgsql security definer set search_path='' as $$
declare v_user_id uuid:=auth.uid(); begin
 if v_user_id is null then raise exception using errcode='42501',message='authentication_required'; end if;
 if p_blocked_id is null or p_blocked_id=v_user_id then raise exception using errcode='22023',message='invalid_block_target'; end if;
 if not exists(select 1 from public.profiles p where p.id=p_blocked_id) then raise exception using errcode='23503',message='block_target_not_found'; end if;
 insert into public.user_blocks(blocker_id,blocked_id,reason_code) values(v_user_id,p_blocked_id,nullif(btrim(p_reason_code),'')) on conflict(blocker_id,blocked_id) do update set reason_code=excluded.reason_code;
 update public.friendships f set status='cancelled'::public.friendship_status,responded_at=coalesce(f.responded_at,now()) where f.pair_low_id=least(v_user_id,p_blocked_id) and f.pair_high_id=greatest(v_user_id,p_blocked_id) and f.status in ('pending','accepted');
 return true;
end $$;
